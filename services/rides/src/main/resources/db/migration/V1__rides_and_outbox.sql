CREATE TABLE rides (
    id UUID PRIMARY KEY,
    user_id UUID NOT NULL,
    vehicle_id UUID NOT NULL,
    reservation_id UUID,
    origin_zone_id UUID NOT NULL,
    destination_zone_id UUID,
    active_vehicle_id UUID UNIQUE,
    active_user_id UUID UNIQUE,
    vehicle_type VARCHAR(20) NOT NULL CHECK (vehicle_type IN ('BICYCLE', 'SCOOTER')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('IN_PROGRESS', 'FINISHED')),
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE,
    duration_seconds BIGINT,
    unlock_fee NUMERIC(12,2) NOT NULL CHECK (unlock_fee >= 0),
    price_per_minute NUMERIC(12,2) NOT NULL CHECK (price_per_minute >= 0),
    preliminary_cost NUMERIC(12,2),
    currency VARCHAR(3) NOT NULL,
    start_key VARCHAR(128) NOT NULL UNIQUE,
    finish_key VARCHAR(128) UNIQUE,
    CHECK ((status = 'IN_PROGRESS' AND active_vehicle_id = vehicle_id AND active_user_id = user_id
            AND active_vehicle_id IS NOT NULL AND active_user_id IS NOT NULL AND finished_at IS NULL)
        OR (status = 'FINISHED' AND active_vehicle_id IS NULL AND active_user_id IS NULL
            AND finished_at IS NOT NULL AND destination_zone_id IS NOT NULL
            AND duration_seconds >= 0 AND preliminary_cost IS NOT NULL AND finish_key IS NOT NULL))
);
CREATE INDEX rides_user_started_idx ON rides(user_id, started_at);
CREATE TABLE outbox_events (
    sequence_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL UNIQUE,
    event_type VARCHAR(50) NOT NULL,
    payload TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE,
    attempts INTEGER NOT NULL DEFAULT 0,
    last_error VARCHAR(255)
);
CREATE INDEX outbox_pending_idx ON outbox_events(published_at, next_attempt_at, sequence_id);
